/* anchors: the passage of a post that a comment quotes (streampack#256), in the browser.

   A comment's anchor is a W3C Web Annotation text quote selector: the quoted text (exact), and
   some of the post's text before it (prefix) and after it (suffix). streampack checks the quote
   against the post's text, as its database function html_text() makes it. This module makes the
   same text from the post's DOM, so a quote made here is a quote the server accepts:

     - an element in BLOCKS is a space at its start and at its end;
     - any other element adds nothing, but its text stays;
     - entities are already decoded in the DOM;
     - each run of WHITESPACE is one space, and the text has no space at either end.

   test/fixtures/text.json holds HTML and the text that html_text() makes of it, generated by
   running that function. The tests check this module against it.

   No dependencies, no framework, and nothing drawn: each front end draws its own callouts. */

/** The most characters (UTF-16 code units, as the server counts them) that a quote can have. */
export const MAX_EXACT = 500;

/** The most characters that a prefix or a suffix can have. */
export const MAX_CONTEXT = 64;

/** The elements that html_text() makes a space at each end of. Others add nothing. */
const BLOCKS = new Set([
  'p', 'br', 'hr', 'li', 'ul', 'ol', 'dl', 'dt', 'dd', 'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'div',
  'pre', 'blockquote', 'table', 'thead', 'tbody', 'tr', 'td', 'th', 'figure', 'figcaption',
  'section', 'article', 'aside', 'header', 'footer', 'details', 'summary',
]);

/**
 * The characters that html_text() makes into one space. They are the characters that the
 * database's `\s` matches (PostgreSQL, en_US.utf8), and U+00A0. The stored HTML writes U+00A0 as
 * `&nbsp;`, which html_text() makes a space; the DOM gives it back as U+00A0.
 */
const WHITESPACE = /[\t\n\v\f\r \u00a0\u1680\u2000-\u2006\u2008-\u200a\u2028\u2029\u205f\u3000]/;

const ELEMENT = 1;
const TEXT = 3;

/**
 * Makes the text of a post, as html_text() makes it, with a DOM position for each character.
 *
 * A position is a boundary point: a node and an offset, as a Range takes them. A character from a
 * text node starts at its offset in that node and ends one code unit later. A space that a block
 * element makes starts and ends at the same point, just before or just after that element. A space
 * that stands for a run of whitespace starts where the run starts and ends where the run ends.
 *
 * @param {Node} root the element that holds the post's HTML, and nothing else. Its own tag adds
 *   no space.
 * @param {{ignore?: string}} [options] `ignore` is a CSS selector. Elements that match it, and
 *   everything in them, are left out. Use it for what the front end adds to the post, such as a
 *   code block's copy button.
 * @returns {{text: string, starts: Array<[Node, number]>, ends: Array<[Node, number]>}} the text,
 *   and for each of its characters the point where it starts and the point where it ends. The
 *   three have the same length.
 */
export function textModel(root, options = {}) {
  const ignore = options.ignore;
  let text = '';
  const starts = [];
  const ends = [];
  let run = null; // The whitespace not yet written: [start, end] of the run.

  const space = (start, end) => {
    if (run) run[1] = end;
    else run = [start, end];
  };
  const char = (c, start, end) => {
    // A run of whitespace is written only before a character that follows it: so not at the start
    // of the text, and not at its end.
    if (run && text.length > 0) {
      text += ' ';
      starts.push(run[0]);
      ends.push(run[1]);
    }
    run = null;
    text += c;
    starts.push(start);
    ends.push(end);
  };

  const walk = (parent) => {
    let index = 0;
    for (let node = parent.firstChild; node; node = node.nextSibling, index++) {
      if (node.nodeType === TEXT) {
        const data = node.data;
        for (let i = 0; i < data.length; i++) {
          const c = data[i];
          if (WHITESPACE.test(c)) space([node, i], [node, i + 1]);
          else char(c, [node, i], [node, i + 1]);
        }
      } else if (node.nodeType === ELEMENT) {
        if (ignore && node.matches(ignore)) continue;
        const block = BLOCKS.has(node.localName.toLowerCase());
        if (block) space([parent, index], [parent, index]);
        walk(node);
        if (block) space([parent, index + 1], [parent, index + 1]);
      }
    }
  };
  walk(root);
  return { text, starts, ends };
}

/**
 * Makes the text of a post, as html_text() makes it.
 *
 * @param {Node} root the element that holds the post's HTML.
 * @param {{ignore?: string}} [options] as for [textModel].
 * @returns {string} the text. It is empty when the post has no text.
 */
export function textOf(root, options) {
  return textModel(root, options).text;
}

/**
 * Makes a string's whitespace as html_text() makes it: each run of WHITESPACE one space, and no
 * space at either end.
 *
 * @param {string} value any text.
 * @returns {string} the text with its whitespace collapsed.
 */
export function collapse(value) {
  return value.split(new RegExp(WHITESPACE.source + '+')).filter(Boolean).join(' ');
}

/**
 * Makes the anchor for a selection in a post.
 *
 * The quote is the post's text that the range covers: each character whose start and end are both
 * in the range. Spaces at its ends are removed. The prefix is up to MAX_CONTEXT characters of the
 * post's text before the quote, and the suffix up to MAX_CONTEXT after it. Neither cuts a
 * character that takes two code units (such as an emoji) in half.
 *
 * Part of a range outside the root adds nothing.
 *
 * @param {Range} range the selection, usually `getSelection().getRangeAt(0)`.
 * @param {Node} root the element that holds the post's HTML.
 * @param {{ignore?: string}} [options] as for [textModel].
 * @returns {{anchor: {exact: string, prefix: string | null, suffix: string | null}} |
 *   {refused: 'empty'} | {refused: 'too-long', length: number}} the anchor to send. Or why there
 *   is none: the range covers no text, or its quote is longer than MAX_EXACT (`length` says how
 *   long, so a front end can say so).
 */
export function anchorFrom(range, root, options) {
  const { text, starts, ends } = textModel(root, options);
  const inside = ([node, offset]) => {
    try {
      return range.comparePoint(node, offset) === 0;
    } catch {
      return false; // A point in another document or tree is not in the range.
    }
  };
  let a = -1;
  let b = -1;
  for (let i = 0; i < text.length; i++) {
    if (inside(starts[i]) && inside(ends[i])) {
      if (a < 0) a = i;
      b = i + 1;
    }
  }
  if (a < 0) return { refused: 'empty' };
  while (a < b && text[a] === ' ') a++;
  while (b > a && text[b - 1] === ' ') b--;
  if (a === b) return { refused: 'empty' };
  const exact = text.slice(a, b);
  if (exact.length > MAX_EXACT) return { refused: 'too-long', length: exact.length };
  return { anchor: { exact, prefix: before(text, a), suffix: after(text, b) } };
}

/** Up to MAX_CONTEXT code units of [text] just before [at], or null. No half characters. */
function before(text, at) {
  let from = Math.max(0, at - MAX_CONTEXT);
  if (from > 0 && isLow(text.charCodeAt(from))) from++;
  return text.slice(from, at) || null;
}

/** Up to MAX_CONTEXT code units of [text] just after [at], or null. No half characters. */
function after(text, at) {
  let to = Math.min(text.length, at + MAX_CONTEXT);
  if (to < text.length && isLow(text.charCodeAt(to))) to--;
  return text.slice(at, to) || null;
}

/** Whether [code] is the second half of a character that takes two code units. */
const isLow = (code) => code >= 0xdc00 && code <= 0xdfff;

/**
 * Finds each comment's passage in a post, and groups comments that quote the same passage.
 *
 * Each quote is looked for in the post's text. When it occurs more than once, the occurrence whose
 * text before it ends most like the prefix, and whose text after it starts most like the suffix,
 * wins; on a tie, the first wins. A quote that doesn't occur is an orphan: an edit of the post
 * removed it.
 *
 * Comments are in one group when their passages start and end at the same characters, even if
 * their prefixes or suffixes differ.
 *
 * @param {Array<{id: string, anchor: {exact: string, prefix?: string | null,
 *   suffix?: string | null}}>} entries the anchored comments, as the API gives them.
 * @param {Node} root the element that holds the post's HTML.
 * @param {{ignore?: string}} [options] as for [textModel].
 * @returns {{found: Array<{ids: string[], start: number, end: number, range: Range}>,
 *   orphans: string[]}} the passages in the order they occur in the post, each with its comments'
 *   ids in the order given, its place in the text (`end` is exclusive) and a Range over it; and the
 *   ids of the comments whose passage is gone.
 */
export function locate(entries, root, options) {
  const { text, starts, ends } = textModel(root, options);
  const groups = new Map();
  const orphans = [];
  for (const { id, anchor } of entries) {
    const exact = collapse(anchor?.exact ?? '');
    const at = exact ? best(text, exact, anchor.prefix ?? '', anchor.suffix ?? '') : -1;
    if (at < 0) {
      orphans.push(id);
      continue;
    }
    const key = at + ':' + (at + exact.length);
    const group = groups.get(key);
    if (group) group.ids.push(id);
    else groups.set(key, { ids: [id], start: at, end: at + exact.length });
  }
  const doc = root.ownerDocument ?? root;
  const found = [...groups.values()].sort((x, y) => x.start - y.start || x.end - y.end);
  for (const group of found) {
    const range = doc.createRange();
    range.setStart(...starts[group.start]);
    range.setEnd(...ends[group.end - 1]);
    group.range = range;
  }
  return { found, orphans };
}

/**
 * Finds a passage given only its anchor.
 *
 * @param {{exact: string, prefix?: string | null, suffix?: string | null}} anchor the anchor.
 * @param {Node} root the element that holds the post's HTML.
 * @param {{ignore?: string}} [options] as for [textModel].
 * @returns {Range | null} a Range over the passage, or null when the post doesn't hold it.
 */
export function rangeFor(anchor, root, options) {
  return locate([{ id: '', anchor }], root, options).found[0]?.range ?? null;
}

/** Where [exact] occurs in [text] with the context most like [prefix] and [suffix], or -1. */
function best(text, exact, prefix, suffix) {
  let winner = -1;
  let score = -1;
  for (let at = text.indexOf(exact); at >= 0; at = text.indexOf(exact, at + 1)) {
    const here = endsAlike(text, at, prefix) + startsAlike(text, at + exact.length, suffix);
    if (here > score) {
      winner = at;
      score = here;
    }
  }
  return winner;
}

/** How many characters of [text] just before [at] are the same as the end of [prefix]. */
function endsAlike(text, at, prefix) {
  let n = 0;
  while (n < prefix.length && n < at && text[at - 1 - n] === prefix[prefix.length - 1 - n]) n++;
  return n;
}

/** How many characters of [text] from [at] are the same as the start of [suffix]. */
function startsAlike(text, at, suffix) {
  let n = 0;
  while (n < suffix.length && at + n < text.length && text[at + n] === suffix[n]) n++;
  return n;
}

/**
 * Works out where each callout goes in the margin, so that none overlap.
 *
 * Each callout wants to be level with its passage. Callouts are taken from the top down, in the
 * order of the place they want; one that would overlap the callout above it moves down until it
 * doesn't. This works on numbers only: the front end measures, and draws where this says.
 *
 * @param {Array<{key: string, top: number, height: number}>} items for each callout: a key the
 *   front end knows it by, the top it wants (usually its passage's top, in the margin's own
 *   coordinates), and its height. Any unit, if all three use the same one.
 * @param {{gap?: number, top?: number}} [options] `gap` is the least space between two callouts
 *   (8 if not given). `top` is the highest a callout can go (0 if not given).
 * @returns {Array<{key: string, top: number, shift: number}>} for each item, in the order given,
 *   the top it goes at and how far that is below the top it wanted (0 or more).
 */
export function place(items, options = {}) {
  const gap = options.gap ?? 8;
  const ceiling = options.top ?? 0;
  const order = items.map((item, i) => i).sort((x, y) => items[x].top - items[y].top || x - y);
  const out = new Array(items.length);
  let floor = -Infinity;
  for (const i of order) {
    const { key, top, height } = items[i];
    const at = Math.max(top, ceiling, floor);
    out[i] = { key, top: at, shift: at - top };
    floor = at + height + gap;
  }
  return out;
}

/**
 * Marks passages lightly with the CSS Custom Highlight API, without changing the post's DOM.
 *
 * Style the mark with `::highlight(name)` in CSS. A browser without the API gets no mark, and this
 * returns false, so the front end can draw its own (for example a bar in the margin).
 *
 * @param {Iterable<Range>} ranges the passages, such as the ranges from [locate].
 * @param {string} [name] the highlight's name; "comment-anchor" if not given. A second call with
 *   the same name replaces the first.
 * @returns {boolean} true when the passages are marked.
 */
export function mark(ranges, name = 'comment-anchor') {
  const highlights = globalThis.CSS?.highlights;
  if (!highlights || typeof globalThis.Highlight !== 'function') return false;
  highlights.set(name, new globalThis.Highlight(...ranges));
  return true;
}

/**
 * Removes the marks that [mark] made with this name.
 *
 * @param {string} [name] the highlight's name; "comment-anchor" if not given.
 */
export function unmark(name = 'comment-anchor') {
  globalThis.CSS?.highlights?.delete(name);
}
